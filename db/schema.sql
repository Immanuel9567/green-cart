-- GreenCart shared storefront state.
--
-- ONE ROW PER DOCUMENT. The storefront keeps its catalogue, promotions and
-- customer statuses in a single JSON document (js/store.js). Rather than
-- normalising that into twelve tables for a shop with fourteen products, the
-- document is stored whole, in one row, in `shop_state`. That keeps a single
-- source of truth and makes the write atomic: the browser reads a document and
-- writes a document, and two shops never see a half-updated catalogue.
--
-- ORDERS ARE THE EXCEPTION and deliberately so. An order is a financial record;
-- it gets its own table with the money broken into integer minor units, so no
-- amount is ever a float and no report can round a naira away. Orders are append
-- only from the shop's point of view: a status may advance, the money may not
-- change.
--
-- WHY THE MONEY IS STORED TWICE (USD cents and NGN kobo, plus the rate):
-- prices are authored in USD, charged in NGN, and the exchange rate moves. If
-- only the converted figure were stored, a rate change would silently rewrite
-- what a customer was charged. Storing both and the rate used means an order
-- always reconciles to the figures it was placed at.
--
-- This schema is plain Postgres and is written to run on Supabase unchanged.
-- Every statement is idempotent so it can be applied on every cold start
-- without dropping data.

-- The storefront document: products, promotions, customer statuses.
CREATE TABLE IF NOT EXISTS shop_state (
  -- There is exactly one live document. The primary key makes that structural:
  -- a second row cannot be inserted by accident.
  id            TEXT PRIMARY KEY DEFAULT 'default',
  -- The document itself. `jsonb` so the server can query into it later without
  -- a migration, and so Postgres validates it is well-formed JSON on write.
  doc           JSONB NOT NULL,
  -- Optimistic concurrency. The browser sends the version it last read; a write
  -- carrying a stale version is rejected rather than silently overwriting a
  -- change made on another device. NULL-safe via the default.
  version       INTEGER NOT NULL DEFAULT 1,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT shop_state_id_check CHECK (id = 'default')
);

-- Orders. One row per paid or attempted order, keyed by the payment reference so
-- a retried webhook cannot duplicate one.
CREATE TABLE IF NOT EXISTS orders (
  -- A surrogate key, used only to impose a stable order on the list. Two orders
  -- can be created in the same millisecond; `created_at` alone cannot break the
  -- tie, and "newest first" must be deterministic or the owner's list jumps
  -- around between refreshes. This is portable across Postgres and SQLite,
  -- which a SQLite-only `rowid` would not be.
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- The customer-facing reference, e.g. GC-2026-ABC123. Unique, because it is
  -- what the customer quotes and what the payment provider sends back — but not
  -- the primary key, so the ordering column stays independent of it.
  reference       TEXT NOT NULL UNIQUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Fulfilment state. Separate from payment state on purpose: an order can be
  -- paid and not yet shipped.
  status          TEXT NOT NULL DEFAULT 'pending',
  CONSTRAINT orders_status_check
    CHECK (status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded')),

  -- Payment state and the evidence for it. `payment_status` is never inferred
  -- from a browser claim; the server writes it after verifying with the provider
  -- or after taking a pay-on-delivery order.
  payment_status  TEXT NOT NULL DEFAULT 'none',
  CONSTRAINT orders_payment_status_check
    CHECK (payment_status IN ('none', 'paid', 'unverified', 'refunded')),
  payment_provider TEXT NOT NULL DEFAULT '',
  -- When the money was confirmed. NULL for pay-on-delivery until it is collected.
  paid_at         TIMESTAMPTZ,

  -- Customer. Email is not a foreign key: a shop must be able to record an order
  -- from someone who has never made an account.
  customer_name   TEXT NOT NULL DEFAULT '',
  customer_email  TEXT NOT NULL DEFAULT '',
  customer_address TEXT NOT NULL DEFAULT '',
  customer_city   TEXT NOT NULL DEFAULT '',

  -- Money. Integer minor units only. `usd_total_cents` is the authored figure,
  -- `amount_kobo` is the charge, and `ngn_per_usd` records the rate that linked
  -- them so history cannot be rewritten by a later rate change.
  currency        TEXT NOT NULL DEFAULT 'NGN',
  CONSTRAINT orders_currency_check CHECK (currency = 'NGN'),
  amount_kobo     BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT orders_amount_kobo_check CHECK (amount_kobo >= 0),
  usd_total_cents BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT orders_usd_check CHECK (usd_total_cents >= 0),
  ngn_per_usd     NUMERIC(12, 4),
  promo_code      TEXT NOT NULL DEFAULT '',

  -- The line items as JSON, denormalised on purpose. A product's price changes;
  -- an order's price must not. Copying the snapshot in means editing the
  -- catalogue tomorrow cannot alter what a customer bought today.
  items           JSONB NOT NULL DEFAULT '[]'::jsonb
);

CREATE INDEX IF NOT EXISTS orders_created_at_idx ON orders (created_at DESC);
CREATE INDEX IF NOT EXISTS orders_email_idx ON orders (lower(customer_email));
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status);

-- Append-only audit of everything that touched an order's payment. Never
-- updated, never deleted: this is how a disputed charge is reconstructed.
CREATE TABLE IF NOT EXISTS payment_events (
  id          BIGSERIAL PRIMARY KEY,
  reference   TEXT NOT NULL,
  event       TEXT NOT NULL,
  outcome     TEXT NOT NULL DEFAULT '',
  detail      TEXT NOT NULL DEFAULT '',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS payment_events_reference_idx ON payment_events (reference, created_at DESC);
